def norm(t):
    t = unicodedata.normalize('NFKC', t)
    t = re.sub(r'[ً-ٰٟـ]', '', t)
    t = re.sub(r'@Q[BE]@|ms\d+|PageV\d+P\d+|[()\[\]«»"\'.,،؛:؟!\-–]|\d+', ' ', t)
    t = t.replace('أ', 'أ').replace('ٱ', 'ا')
    return re.sub(r'\s+', ' ', t).strip()


def nn(s):  # karşılaştırma için hemzesiz biçim
    return re.sub('[أإآ]', 'ا', s).replace('ة', 'ه').replace('ى', 'ي')


